package com.library.borrow.domain;

public enum BorrowStatus {

    /** Сага началась: выдача создана, экземпляр в каталоге ещё не закреплён. */
    PENDING,
    /** Книга на руках. */
    ACTIVE,
    /** Срок возврата прошёл. */
    OVERDUE,
    /** Книга возвращена. */
    RETURNED,
    /** Сага откатилась: читатель заблокирован, нет экземпляров или каталог недоступен. */
    REJECTED
}
